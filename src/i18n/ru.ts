/**
 * Russian text for the client-facing report.
 *
 * The CLI stays in English: it is read by the person who runs it, and that person reads
 * English error messages all day. The report is different — it is handed to whoever
 * commissioned the work, and in the market where ГОСТ Р 52872-2019 gets written into a
 * procurement contract that person does not necessarily read English at all. A
 * half-translated deliverable is worse than an English one, so this table covers every
 * rule and a test fails the build when a rule is added without its Russian text.
 *
 * The per-rule text is deliberately general where the English is specific. An English
 * `impact` can name the file — "a screen reader announces hero.png" — because it is
 * composed per finding. Composing Russian sentences from fragments produces the kind of
 * prose that tells a reader a machine wrote it, so the Russian says what is true of
 * every occurrence of the rule and lets the quoted source line supply the specifics.
 *
 * `patch` is what the offered edit does; `manual` is what a person has to do when no
 * edit is offered. Both are needed: the same rule reaches both states depending on what
 * it found.
 */

